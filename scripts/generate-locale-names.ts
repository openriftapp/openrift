// Writes apps/web/src/lib/country-names/ (one module per locale, in collation order, and the
// loaders) and apps/web/src/lib/language-names.gen.ts from the CLDR files in scripts/data/cldr-<version>/.
//
//   bun run locale-names:generate          rewrite the modules
//   bun run locale-names:generate --check  exit 1 when the committed modules are stale

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { FLAG_CODES } from "../apps/web/src/lib/flag-codes.js";
import { cldrLanguageName } from "./cldr-language-name.js";

const SHORT_NAME_CODES = new Set(["HK", "MO", "PS"]);
const UNNAMED_CODES = new Set(["pc", "xx", "zz"]);
const CARD_LANGUAGE_TAGS: Readonly<Record<string, string>> = {
  EN: "en",
  FR: "fr",
  KR: "ko",
  SC: "zh-Hans",
  TC: "zh-Hant",
};
const HEADER = "// Generated by scripts/generate-locale-names.ts. Do not edit.\n";

interface CldrFile<T> {
  main: Record<string, { localeDisplayNames: T }>;
}

const repoRoot = resolve(import.meta.dirname, "..");
const countryDir = join(repoRoot, "apps/web/src/lib/country-names");
const languageFile = join(repoRoot, "apps/web/src/lib/language-names.gen.ts");
const cldrDir = join(repoRoot, "scripts/data/cldr-48.2.0");

const settings = JSON.parse(
  readFileSync(join(repoRoot, "apps/web/project.inlang/settings.json"), "utf-8"),
) as { locales: string[] };
const locales = settings.locales.toSorted();

function cldr<T>(locale: string, file: string): T {
  const parsed = JSON.parse(readFileSync(join(cldrDir, locale, file), "utf-8")) as CldrFile<T>;
  const entry = parsed.main[locale];
  if (entry === undefined) {
    throw new Error(`CLDR ${file} has no entry for ${locale}`);
  }
  return entry.localeDisplayNames;
}

function territories(locale: string): Record<string, string> {
  return cldr<{ territories: Record<string, string> }>(locale, "territories.json").territories;
}

function languageName(locale: string, tag: string): string {
  const { languages } = cldr<{ languages: Record<string, string> }>(locale, "languages.json");
  const name =
    cldrLanguageName({ languages }, tag) ??
    cldrLanguageName(
      {
        languages,
        scripts: cldr<{ scripts: Record<string, string> }>(locale, "scripts.json").scripts,
        localePattern: cldr<{ localeDisplayPattern: { localePattern: string } }>(
          locale,
          "localeDisplayNames.json",
        ).localeDisplayPattern.localePattern,
      },
      tag,
    );
  if (name === undefined) {
    throw new Error(`CLDR has no ${locale} name for ${tag}`);
  }
  return name;
}

function localeModule(locale: string): string {
  const names = territories(locale);
  const collator = new Intl.Collator(locale);
  const entries = [...FLAG_CODES]
    .filter((flag) => !UNNAMED_CODES.has(flag))
    .map((code): [string, string] => {
      const upper = code.toUpperCase();
      const name =
        (SHORT_NAME_CODES.has(upper) ? names[`${upper}-alt-short`] : undefined) ?? names[upper];
      if (name === undefined) {
        throw new Error(`CLDR has no ${locale} name for ${upper}`);
      }
      return [code, name];
    })
    .toSorted(
      ([codeA, nameA], [codeB, nameB]) =>
        collator.compare(nameA, nameB) || (codeA < codeB ? -1 : 1),
    );
  const lines = entries.map(([code, name]) => `  ${code}: ${JSON.stringify(name)},`);
  return `${HEADER}const COUNTRY_NAMES: Readonly<Record<string, string>> = {
${lines.join("\n")}
};

export default COUNTRY_NAMES;
`;
}

function propertyKey(locale: string): string {
  return /^[a-z]+$/u.test(locale) ? locale : JSON.stringify(locale);
}

function languageNamesModule(): string {
  const blocks = locales.map((locale) => {
    const lines = Object.entries(CARD_LANGUAGE_TAGS).map(
      ([code, tag]) => `    ${code}: ${JSON.stringify(languageName(locale, tag))},`,
    );
    return `  ${propertyKey(locale)}: {\n${lines.join("\n")}\n  },`;
  });
  return `${HEADER}import type { Locale } from "@/paraglide/runtime.js";

export const LANGUAGE_NAMES: Readonly<Record<Locale, Readonly<Record<string, string>>>> = {
${blocks.join("\n")}
};
`;
}

const loaders = `${HEADER}import type { Locale } from "@/paraglide/runtime.js";

export type CountryNames = Readonly<Record<string, string>>;

export const COUNTRY_NAME_LOADERS: Readonly<
  Record<Locale, () => Promise<{ default: CountryNames }>>
> = {
${locales.map((locale) => `  ${propertyKey(locale)}: () => import("./${locale}.gen"),`).join("\n")}
};
`;

const countryFiles = new Map<string, string>([
  ["loaders.gen.ts", loaders],
  ...locales.map((locale): [string, string] => [`${locale}.gen.ts`, localeModule(locale)]),
]);
const files = new Map<string, string>([
  ...[...countryFiles].map(([file, source]): [string, string] => [join(countryDir, file), source]),
  [languageFile, languageNamesModule()],
]);

function strayCountryFiles(): string[] {
  try {
    return readdirSync(countryDir)
      .filter((file) => !countryFiles.has(file))
      .map((file) => join(countryDir, file));
  } catch {
    return [];
  }
}

function readOrNull(path: string): string | null {
  try {
    return readFileSync(path, "utf-8");
  } catch {
    return null;
  }
}

if (process.argv.includes("--check")) {
  const stale = [
    ...strayCountryFiles(),
    ...[...files].filter(([path, source]) => readOrNull(path) !== source).map(([path]) => path),
  ];
  if (stale.length > 0) {
    console.error(
      `Stale generated names: ${stale.join(", ")}. Run \`bun run locale-names:generate\`.`,
    );
    process.exit(1);
  }
} else {
  mkdirSync(countryDir, { recursive: true });
  for (const path of strayCountryFiles()) {
    rmSync(path);
  }
  for (const [path, source] of files) {
    writeFileSync(path, source);
  }
  console.log(`wrote ${files.size} files`);
}
